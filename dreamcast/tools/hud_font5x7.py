CELL_W, CELL_H = 8, 16   # the cell; the glyph's 6x14 sits at (1, 1)


def rows5(ch):
    """The glyph's seven rows as 5-bit masks, bit 4 the leftmost pixel."""
    g = GLYPHS.get(ch, GLYPHS['?'])
    return [sum(1 << (4 - i) for i, c in enumerate(r) if c == '#') for r in g]


def bold6(m):
    """A 5-bit row made bold, 6 bits (bit 5 the leftmost): each pixel and the
    one to its right, unless that would close a one-pixel gap (m, w, M, #)."""
    return (m << 1 | (m & ~(m << 2))) & 0x3F


def cell(ch):
    """The cell as drawn on the disc: CELL_H rows of CELL_W pixels (0/1)."""
    out = [[0] * CELL_W for _ in range(CELL_H)]
    for y, m in enumerate(rows5(ch)):
        bold = bold6(m)
        for x in range(6):
            if bold >> (5 - x) & 1:
                out[1 + 2 * y][1 + x] = out[2 + 2 * y][1 + x] = 1
    return out


def crc8(s):
    """The panel lines' check: CRC-8 (poly 0x07) of the line's text."""
    c = 0
    for b in s.encode('ascii'):
        c ^= b
        for _ in range(8):
            c = (c << 1 ^ 0x07) & 0xFF if c & 0x80 else c << 1 & 0xFF
    return c


def header():
    assert len(GLYPHS) == 95 and all(len(g) == 7 and all(len(r) == 5 for r in g) for g in GLYPHS.values())
    out = ["/* dc_hudfont.h -- the HUD=prof panel's font, ASCII 32-126 (Pinboard #518).",
           " * Generated by tools/hud_font5x7.py: edit that, not this. A glyph is",
           " * seven 6-bit rows, already bold (bold6), bit 5 the leftmost pixel;",
           " * dc_pvr.h draws each row twice, at (1, 1) in an 8x16 cell. */",
           "#ifndef DC_HUDFONT_H", "#define DC_HUDFONT_H", "",
           "#include <stdint.h>", "",
           "static const uint8_t g_hudfont[95][7] = {"]
    for code in range(32, 127):
        ch = chr(code)
        rows = ", ".join(f"0x{bold6(m):02X}" for m in rows5(ch))
        name = {'\\': 'backslash', '*': 'star', '/': 'slash'}.get(ch, ch)
        out.append(f"    {{ {rows} }},   /* {name} */")
    out += ["};", "", "#endif /* DC_HUDFONT_H */", ""]
    return "\n".join(out)


