#!/usr/bin/env python3
"""Import Kenney's Input Prompts (CC0, https://kenney.nl/assets/input-prompts).

    python3 tools/prompts/import_kenney.py <unzipped kenney_input-prompts dir>
    python3 tools/prompts/import_kenney.py            # regenerate the header only

Copies the icons the web page shows (WEB below) into web/site/prompts/, with
Kenney's License.txt, and writes src/ui/input_prompts.h: the icons the PS3-style
menus draw (MENU below) as path data for ps3ui's rasterizer. The header is made
from the copies in web/site/prompts/, so the pack is needed only to add icons.

The menus' icons are each one filled <path>, nonzero, with only M, L and Q
commands on a 64x64 canvas, which is what ps3ui_path_move/line/quad take
(parse() refuses anything else).
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, 'web', 'site', 'prompts')
HEADER = os.path.join(ROOT, 'src', 'ui', 'input_prompts.h')

PS = 'PlayStation Series/Vector/'
XB = 'Xbox Series/Vector/'
NS = 'Nintendo Switch/Vector/'
KB = 'Keyboard & Mouse/Vector/'

DIRS = ['up', 'down', 'left', 'right']

# The web page's icons (m2hle-prompts.js), by the pack's own names.
WEB = (
    [PS + 'playstation_button_color_' + b for b in ('cross', 'circle', 'square', 'triangle')]
    + [PS + 'playstation_trigger_' + b for b in ('l1', 'r1', 'l2', 'r2')]
    + [PS + 'playstation_button_' + b for b in ('l3', 'r3')]
    + [PS + 'playstation3_button_select', PS + 'playstation3_button_start',
       PS + 'playstation4_button_share', PS + 'playstation4_button_options',
       PS + 'playstation5_button_create', PS + 'playstation5_button_options']
    + [PS + 'playstation_dpad_' + d for d in DIRS]
    + [PS + 'playstation_stick_' + s + '_' + d for s in 'lr' for d in DIRS]
    + [PS + 'controller_playstation3']
    + [XB + 'xbox_button_color_' + b for b in 'abxy']
    + [XB + 'xbox_' + b for b in ('lb', 'rb', 'lt', 'rt', 'ls', 'rs', 'guide')]
    + [XB + 'xbox_button_view', XB + 'xbox_button_menu']
    + [XB + 'xbox_dpad_' + d for d in DIRS]
    + [XB + 'xbox_stick_' + s + '_' + d for s in 'lr' for d in DIRS]
    + [NS + 'switch_button_' + b for b in ('a', 'b', 'x', 'y', 'l', 'r', 'zl', 'zr', 'minus', 'plus', 'home')]
    + [NS + 'switch_stick_' + s + '_press' for s in 'lr']
    + [NS + 'switch_dpad_' + d for d in DIRS]
    + [NS + 'switch_stick_' + s + '_' + d for s in 'lr' for d in DIRS]
    + [KB + 'keyboard_' + c for c in 'abcdefghijklmnopqrstuvwxyz0123456789']
    + [KB + 'keyboard_arrow_' + d for d in DIRS]
    + [KB + 'keyboard_' + k for k in ('space', 'enter', 'shift', 'ctrl', 'alt', 'tab', 'escape', 'backspace',
                                       'comma', 'period', 'slash_forward', 'semicolon', 'apostrophe', 'minus',
                                       'equals', 'bracket_open', 'bracket_close')]
)

# The menus' icons: (C name, file in web/site/prompts, colour or None for the file's).
MENU = [
    ('CROSS', 'playstation_button_color_cross', None),
    ('CIRCLE', 'playstation_button_color_circle', None),
    ('SQUARE', 'playstation_button_color_square', None),
    ('TRIANGLE', 'playstation_button_color_triangle', None),
    ('L1', 'playstation_trigger_l1', None),
    ('L2', 'playstation_trigger_l2', None),
    ('R1', 'playstation_trigger_r1', None),
    ('R2', 'playstation_trigger_r2', None),
    ('PAD_PS3', 'controller_playstation3', None),
]

PATH_MAX, CONTOURS_MAX, QUAD_STEPS = 1024, 64, 8   # ps3ui.h


def parse(svg):
    """(rgb, [contour, ...]) where a contour is [('M'|'L', x, y) | ('Q', cx, cy, x, y)]."""
    paths = re.findall(r'<path[^>]*>', svg)
    if len(paths) != 1:
        raise ValueError('expected one <path>, found %d' % len(paths))
    fill = re.search(r'fill="#([0-9A-Fa-f]{6})"', paths[0]).group(1)
    d = re.search(r' d="([^"]*)"', paths[0]).group(1)
    toks = re.findall(r'[A-Za-z]|-?[\d.]+', d)
    out, cmd, i = [], None, 0
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            if t not in 'MLQ':
                raise ValueError('path command %s' % t)
            cmd = t
            i += 1
            continue
        v = [float(x) for x in toks[i:i + (4 if cmd == 'Q' else 2)]]
        if cmd == 'M':
            out.append([('M', *v)])
            cmd = 'L'                     # extra pairs after M are lines
        else:
            out[-1].append((cmd, *v))
        i += len(v)
    return int(fill, 16), out


def fmt(v):
    s = ('%.3f' % v).rstrip('0')
    s = s + '0' if s.endswith('.') else s
    return ('0.0' if s == '-0.0' else s) + 'f'


def header():
    lines = [
        '/* Generated by tools/prompts/import_kenney.py from web/site/prompts/ -- do not edit.',
        ' *',
        " * Input prompt icons from Kenney's Input Prompts 1.5A (www.kenney.nl), released",
        ' * under Creative Commons Zero (CC0): web/site/prompts/License.txt. Each icon is',
        ' * its SVG path on a 64x64 canvas, filled with nonzero winding: a run of ops,',
        ' * each an INPUT_PROMPT_* code followed by its points (move and line: x, y; quad:',
        ' * cx, cy, x, y). ps3ui_sprites.h paints them through ps3ui_path_*. */',
        '#ifndef INPUT_PROMPTS_H',
        '#define INPUT_PROMPTS_H',
        '',
        '#include <stdint.h>',
        '',
        'enum { INPUT_PROMPT_MOVE, INPUT_PROMPT_LINE, INPUT_PROMPT_QUAD };',
        '',
        'typedef struct {',
        '    const char *file;       /* web/site/prompts/<file>.svg */',
        '    uint32_t rgb;           /* the fill */',
        '    int n;                  /* floats in d */',
        '    const float *d;',
        '} input_prompt_t;',
        '',
    ]
    names = []
    for name, f, rgb in MENU:
        fill, contours = parse(open(os.path.join(OUT_DIR, f + '.svg'), encoding='utf-8').read())
        pts = sum(1 + sum(QUAD_STEPS if op[0] == 'Q' else 1 for op in c[1:]) for c in contours)
        if pts > PATH_MAX or len(contours) > CONTOURS_MAX:
            raise ValueError('%s: %d points, %d contours: over ps3ui_path_t' % (f, pts, len(contours)))
        vals = []
        for c in contours:
            for op in c:
                vals.append('INPUT_PROMPT_' + {'M': 'MOVE', 'L': 'LINE', 'Q': 'QUAD'}[op[0]])
                vals += [fmt(v) for v in op[1:]]
        lines.append('static const float input_prompt_%s_d[%d] = {' % (name.lower(), len(vals)))
        row = '   '
        for v in vals:
            if len(row) + len(v) + 2 > 116:
                lines.append(row)
                row = '   '
            row += ' ' + v + ','
        lines.append(row)
        lines.append('};')
        names.append((name, f, rgb if rgb is not None else fill, len(vals)))
    lines.append('')
    lines.append('enum {')
    for name, *_ in names:
        lines.append('    INPUT_PROMPT_%s,' % name)
    lines.append('    INPUT_PROMPT_COUNT')
    lines.append('};')
    lines.append('')
    lines.append('static const input_prompt_t input_prompts[INPUT_PROMPT_COUNT] = {')
    for name, f, rgb, n in names:
        lines.append('    { "%s", 0x%06X, %d, input_prompt_%s_d },' % (f, rgb, n, name.lower()))
    lines.append('};')
    lines.append('')
    lines.append('#endif /* INPUT_PROMPTS_H */')
    with open(HEADER, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('wrote', os.path.relpath(HEADER, ROOT))


def main():
    if len(sys.argv) > 1:
        pack = sys.argv[1]
        os.makedirs(OUT_DIR, exist_ok=True)
        for rel in WEB:
            src = os.path.join(pack, rel + '.svg')
            shutil.copyfile(src, os.path.join(OUT_DIR, os.path.basename(rel) + '.svg'))
        shutil.copyfile(os.path.join(pack, 'License.txt'), os.path.join(OUT_DIR, 'License.txt'))
        print('copied %d icons to %s' % (len(WEB), os.path.relpath(OUT_DIR, ROOT)))
    header()


if __name__ == '__main__':
    main()
